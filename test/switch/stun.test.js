import { Stun, Class, Method, encoder } from '../../switch/stun.js';
import { assertEquals } from '@std/assert/mod.ts';

// RFC 5769
Deno.test(async function vector1() {
	const test = new Stun(
		new Uint8Array([
			0x00, 0x01, 0x00, 0x58,
			0x21, 0x12, 0xa4, 0x42,
			0xb7, 0xe7, 0xa7, 0x01,
			0xbc, 0x34, 0xd6, 0x86,
			0xfa, 0x87, 0xdf, 0xae,
			0x80, 0x22, 0x00, 0x10,
			0x53, 0x54, 0x55, 0x4e,
			0x20, 0x74, 0x65, 0x73,
			0x74, 0x20, 0x63, 0x6c,
			0x69, 0x65, 0x6e, 0x74,
			0x00, 0x24, 0x00, 0x04,
			0x6e, 0x00, 0x01, 0xff,
			0x80, 0x29, 0x00, 0x08,
			0x93, 0x2f, 0xf9, 0xb1,
			0x51, 0x26, 0x3b, 0x36,
			0x00, 0x06, 0x00, 0x09,
			0x65, 0x76, 0x74, 0x6a,
			0x3a, 0x68, 0x36, 0x76,
			0x59, 0x20, 0x20, 0x20,
			0x00, 0x08, 0x00, 0x14,
			0x9a, 0xea, 0xa7, 0x0c,
			0xbf, 0xd8, 0xcb, 0x56,
			0x78, 0x1e, 0xf2, 0xb5,
			0xb2, 0xd3, 0xf2, 0x49,
			0xc1, 0xb5, 0x71, 0xa2,
			0x80, 0x28, 0x00, 0x04,
			0xe5, 0x7a, 0x3b, 0xcf,
		]).buffer
	);
	assertEquals(test.class, Class.request, 'STUN class');
	assertEquals(test.method, Method.binding, 'STUN method');
	assertEquals(test.magic, true, 'STUN magic');
	assertEquals(test.software, 'STUN test client', 'ATTR software');
	assertEquals(test.username, 'evtj:h6vY', 'ATTR username');
	const key = await crypto.subtle.importKey('raw', encoder.encode('VOkJxbRl1RmTxUk/WvJxBt'), { name: 'HMAC', hash: 'SHA-1' }, true, ['verify']);
	assertEquals(await test.verify(key), true, 'ATTR integrity');
	assertEquals(test.fingerprint, true, 'STUN fingerprint attribute');
});
